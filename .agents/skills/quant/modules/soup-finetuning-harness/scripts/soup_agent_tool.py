from dataclasses import dataclass
from pathlib import Path
import json
import logging
import os
import shutil
import subprocess
import sys
import time
from typing import Literal, Optional, Dict, Any, List

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("LuminaSoupHarness")

DEFAULT_SOUP_BIN = Path("/Users/malcolm/.local/bin/soup")


def get_soup_executable() -> str:
    """Resolves the soup CLI binary path."""
    if DEFAULT_SOUP_BIN.is_file() and os.access(DEFAULT_SOUP_BIN, os.X_OK):
        return str(DEFAULT_SOUP_BIN)
    which_bin = shutil.which("soup")
    if which_bin:
        return which_bin
    return "soup"


@dataclass(frozen=True)
class SoupBuildConfig:
    project_name: str
    base_model: str
    dataset_path: Path
    recipe_template: Literal["chat", "code", "tool-calling", "reasoning"]
    output_dir: Path
    quant_type: str = "q4_k_m"
    stream_layers: bool = True
    max_seq_len: int = 2048
    epochs: int = 3
    batch_size: int = 1
    gradient_accumulation_steps: int = 4
    lr: float = 2.0e-4
    optimizer: str = "adamw_torch"
    quantization: str = "4bit"


class SoupExecutionHarness:
    """Autonomous execution harness orchestrating Soup CLI adaptation, GGUF export, and Ollama deployment."""

    def __init__(self, workspace_root: Path):
        self.workspace_root = workspace_root.resolve()
        self.recipes_dir = self.workspace_root / "config" / "soup_recipes"
        self.artifacts_dir = self.workspace_root / "artifacts" / "models"
        self._ensure_directories()

    def _ensure_directories(self) -> None:
        self.recipes_dir.mkdir(parents=True, exist_ok=True)
        self.artifacts_dir.mkdir(parents=True, exist_ok=True)

    def generate_recipe(self, config: SoupBuildConfig) -> Path:
        """
        Generates a strictly-typed soup.yaml strictly conforming to Soup CLI v0.75+.
        Avoids all deprecated keys (unknown keys are refused in v0.75+).
        """
        recipe_file = self.recipes_dir / f"{config.project_name}_soup.yaml"
        
        # Validated strictly against Soup CLI v0.75+ schema
        recipe_content = f"""# Auto-generated by Lumina Soup Harness (v0.75+ compliant)
base: "{config.base_model}"
task: "sft"

data:
  train: "{config.dataset_path}"
  val_split: 0.1
  max_length: {config.max_seq_len}

training:
  stream_layers: {'true' if config.stream_layers else 'false'}
  lora:
    r: 16
    alpha: 32
    target_modules: ["q_proj", "v_proj", "k_proj", "o_proj"]
  batch_size: {config.batch_size}
  gradient_accumulation_steps: {config.gradient_accumulation_steps}
  lr: {config.lr}
  epochs: {config.epochs}
  optimizer: "{config.optimizer}"
  quantization: "{config.quantization}"

output: "{config.output_dir}"
"""
        recipe_file.write_text(recipe_content, encoding="utf-8")
        logger.info("Wrote validated training recipe to %s", recipe_file)
        return recipe_file

    def preflight_doctor(self, recipe_path: Path) -> bool:
        """Runs preflight verification via Soup doctor to guarantee recipe and environment compatibility."""
        soup_bin = get_soup_executable()
        cmd = [soup_bin, "doctor", "--config", str(recipe_path.resolve())]
        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        
        # Check for config validation errors in stdout/stderr
        if res.returncode != 0:
            logger.error("Soup doctor rejected recipe:\n%s\n%s", res.stdout, res.stderr)
            return False
        if "Config validation error" in res.stdout or "unknown config key" in res.stdout:
            logger.error("Soup doctor reported validation error:\n%s", res.stdout)
            return False
            
        logger.info("Recipe preflight passed cleanly for %s.", recipe_path.name)
        return True

    def train_and_export(self, config: SoupBuildConfig, dry_run: bool = False) -> Path:
        """
        Executes layer-streamed training, merges weights, and exports GGUF.
        Registers the resulting model into the local Ollama registry.
        """
        soup_bin = get_soup_executable()
        recipe_path = self.generate_recipe(config)
        
        if not self.preflight_doctor(recipe_path):
            raise RuntimeError(f"Preflight validation failed for {recipe_path}")

        gguf_target = self.artifacts_dir / f"{config.project_name}-{config.quant_type}.gguf"

        if dry_run:
            logger.info("[DRY RUN] Simulating training and export pipeline for %s...", config.project_name)
            # Create a mock GGUF stub artifact for test verification
            gguf_target.write_text(f"GGUF_MOCK_MODEL_{config.project_name}_{config.quant_type}\n", encoding="utf-8")
            modelfile = self.artifacts_dir / f"{config.project_name}.Modelfile"
            modelfile.write_text(f"FROM {gguf_target}\nPARAMETER temperature 0.2\n", encoding="utf-8")
            logger.info("[DRY RUN] Pipeline simulation completed successfully: %s", gguf_target)
            return gguf_target

        # 1. Train
        logger.info("Initiating model training via Soup: %s...", recipe_path)
        train_cmd = [soup_bin, "train", "--config", str(recipe_path)]
        res_train = subprocess.run(train_cmd, capture_output=True, text=True, check=False)
        if res_train.returncode != 0:
            raise RuntimeError(f"Training failed with exit code {res_train.returncode}:\n{res_train.stderr}")

        # 2. Export GGUF
        logger.info("Exporting to GGUF format: %s", gguf_target)
        export_cmd = [
            soup_bin, "export",
            "--model", str(config.output_dir),
            "--format", "gguf",
            "--quant", config.quant_type,
            "--output", str(gguf_target)
        ]
        res_export = subprocess.run(export_cmd, capture_output=True, text=True, check=False)
        if res_export.returncode != 0:
            raise RuntimeError(f"GGUF export failed with exit code {res_export.returncode}:\n{res_export.stderr}")

        # 3. Create Ollama Model Definition
        modelfile = self.artifacts_dir / f"{config.project_name}.Modelfile"
        modelfile.write_text(f"FROM {gguf_target}\nPARAMETER temperature 0.2\n", encoding="utf-8")
        
        # 4. Deploy to Ollama
        logger.info("Registering model into local Ollama runtime: %s...", config.project_name)
        ollama_bin = shutil.which("ollama") or "/usr/local/bin/ollama"
        deploy_cmd = [ollama_bin, "create", config.project_name, "-f", str(modelfile)]
        res_deploy = subprocess.run(deploy_cmd, capture_output=True, text=True, check=False)
        if res_deploy.returncode != 0:
            raise RuntimeError(f"Ollama registration failed with exit code {res_deploy.returncode}:\n{res_deploy.stderr}")
            
        logger.info("Model %s successfully registered in Ollama.", config.project_name)
        return gguf_target


# High-level convenience execution wrapper for Antigravity MCP tooling
def run_project_finetune(
    project_id: str,
    dataset: str,
    base_model: str = "meta-llama/Llama-3.1-8B-Instruct",
    template: Literal["chat", "code", "tool-calling", "reasoning"] = "chat",
    workspace_dir: Optional[str] = None,
    dry_run: bool = False
) -> Path:
    ws_path = Path(workspace_dir).resolve() if workspace_dir else Path("./workspace").resolve()
    harness = SoupExecutionHarness(workspace_root=ws_path)
    cfg = SoupBuildConfig(
        project_name=project_id,
        base_model=base_model,
        dataset_path=Path(dataset),
        recipe_template=template,
        output_dir=ws_path / "artifacts" / "adapters" / project_id,
        stream_layers=True
    )
    return harness.train_and_export(cfg, dry_run=dry_run)
