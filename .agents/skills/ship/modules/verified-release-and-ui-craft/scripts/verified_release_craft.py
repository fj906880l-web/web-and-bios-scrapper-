#!/usr/bin/env python3
"""
Verified Release & Tactile UI Craft Helper CLI.

Zero-dependency standard-library toolkit supporting:
1. External security tool availability checks (trufflehog, bla, git)
2. Deterministic SHA-256 artifact manifest generation & verification
3. Static cryptographic separation checks (AES-ECB, MD5/SHA-1, raw SHA-256 password hashing)
4. Frontend AI-slop chrome detection (generic greetings, AI badges, "Powered by AI" footers)
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path
from typing import Any, Dict, List


CRYPTO_ANTI_PATTERNS = [
    ("WEAK_HASH_MD5", re.compile(r"\bhashlib\.md5\s*\(|\bcreateHash\s*\(\s*['\"]md5['\"]", re.IGNORECASE)),
    ("WEAK_HASH_SHA1", re.compile(r"\bhashlib\.sha1\s*\(|\bcreateHash\s*\(\s*['\"]sha1['\"]", re.IGNORECASE)),
    ("INSECURE_AES_ECB", re.compile(r"\bAES\.MODE_ECB\b|aes-\d+-ecb", re.IGNORECASE)),
    (
        "RAW_SHA256_PASSWORD",
        re.compile(r"(?:password|passwd|pwd)\s*.*(?:sha256|sha512)\s*\(", re.IGNORECASE),
    ),
]

UI_SLOP_PATTERNS = [
    ("GENERIC_AI_GREETING", re.compile(r"how can i help you today\??|i['’]m your ai assistant", re.IGNORECASE)),
    ("POWERED_BY_AI_FOOTER", re.compile(r"powered by ai|generated by ai", re.IGNORECASE)),
    ("REDUNDANT_AI_BADGE", re.compile(r">\s*(?:ai[- ]powered|smart assistant)\s*<", re.IGNORECASE)),
]

UI_EXTENSIONS = {".tsx", ".jsx", ".ts", ".js", ".vue", ".svelte", ".html"}
CODE_EXTENSIONS = {".py", ".ts", ".tsx", ".js", ".jsx", ".go", ".rs", ".java", ".rb"}
SKIP_DIRS = {".git", "node_modules", ".next", "dist", "build", "__pycache__", ".venv", "venv"}


def _iter_files(root: Path, extensions: set[str]) -> List[Path]:
    """Recursively collect files matching extensions, skipping build/vendor directories."""
    results: List[Path] = []
    if not root.exists():
        return results
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            p = Path(dirpath) / name
            if p.suffix.lower() in extensions:
                results.append(p)
    return results


def _sha256_file(path: Path) -> str:
    """Compute hex SHA-256 digest for a file."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def cmd_check_tools(_args: argparse.Namespace) -> int:
    """Report availability of external release & audit CLIs."""
    tools = {name: shutil.which(name) for name in ("trufflehog", "bla", "git", "python3")}
    print(json.dumps({"tools": tools}, indent=2))
    return 0


def cmd_sha256_manifest(args: argparse.Namespace) -> int:
    """Generate a deterministic SHA-256 manifest for all files in a directory."""
    target_dir = Path(args.dir).resolve()
    if not target_dir.is_dir():
        print(json.dumps({"error": f"Directory not found: {target_dir}"}), file=sys.stderr)
        return 2

    out_path = Path(args.out).resolve() if args.out else (target_dir / "SHA256SUMS.json")
    artifacts: Dict[str, str] = {}
    for dirpath, dirnames, filenames in os.walk(target_dir):
        dirnames[:] = sorted(d for d in dirnames if d not in {".git", "__pycache__"})
        for name in sorted(filenames):
            file_path = Path(dirpath) / name
            if file_path.resolve() == out_path:
                continue
            rel = file_path.relative_to(target_dir).as_posix()
            artifacts[rel] = _sha256_file(file_path)

    payload: Dict[str, Any] = {
        "algorithm": "sha256",
        "root": str(target_dir),
        "count": len(artifacts),
        "artifacts": artifacts,
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": "ok", "manifest": str(out_path), "count": len(artifacts)}))
    return 0


def cmd_verify_manifest(args: argparse.Namespace) -> int:
    """Verify all files listed in a SHA-256 manifest without path traversal."""
    manifest_path = Path(args.manifest).resolve()
    if not manifest_path.is_file():
        print(json.dumps({"error": f"Manifest not found: {manifest_path}"}), file=sys.stderr)
        return 2

    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    base_dir = Path(args.dir).resolve() if args.dir else manifest_path.parent
    artifacts = data.get("artifacts", {})

    mismatches: List[Dict[str, str]] = []
    missing: List[str] = []
    verified = 0

    for rel, expected_hash in artifacts.items():
        candidate = (base_dir / rel).resolve()
        if not candidate.is_relative_to(base_dir):
            mismatches.append({"file": rel, "reason": "path_traversal_blocked"})
            continue
        if not candidate.is_file():
            missing.append(rel)
            continue
        actual_hash = _sha256_file(candidate)
        if actual_hash != expected_hash:
            mismatches.append({"file": rel, "expected": expected_hash, "actual": actual_hash})
        else:
            verified += 1

    ok = not mismatches and not missing
    print(
        json.dumps(
            {
                "status": "ok" if ok else "failed",
                "verified": verified,
                "missing": missing,
                "mismatches": mismatches,
            },
            indent=2,
        )
    )
    return 0 if ok else 1


def _scan_patterns(root: Path, extensions: set[str], patterns: List[tuple[str, re.Pattern[str]]]) -> List[Dict[str, Any]]:
    """Scan files under root for regex patterns and return structured findings."""
    findings: List[Dict[str, Any]] = []
    for file_path in _iter_files(root, extensions):
        try:
            lines = file_path.read_text(encoding="utf-8", errors="ignore").splitlines()
        except OSError:
            continue
        for lineno, line in enumerate(lines, start=1):
            for rule_id, pattern in patterns:
                if pattern.search(line):
                    findings.append(
                        {
                            "rule": rule_id,
                            "file": str(file_path),
                            "line": lineno,
                            "snippet": line.strip()[:160],
                        }
                    )
    return findings


def cmd_check_crypto_patterns(args: argparse.Namespace) -> int:
    """Scan code directory for prohibited cryptographic anti-patterns."""
    root = Path(args.dir).resolve()
    findings = _scan_patterns(root, CODE_EXTENSIONS, CRYPTO_ANTI_PATTERNS)
    print(json.dumps({"status": "ok" if not findings else "findings", "count": len(findings), "findings": findings}, indent=2))
    return 0 if not findings else 1


def cmd_audit_ui_slop(args: argparse.Namespace) -> int:
    """Scan UI source directory for generic AI chrome and boilerplate slop."""
    root = Path(args.dir).resolve()
    findings = _scan_patterns(root, UI_EXTENSIONS, UI_SLOP_PATTERNS)
    print(json.dumps({"status": "ok" if not findings else "findings", "count": len(findings), "findings": findings}, indent=2))
    return 0 if not findings else 1


def build_parser() -> argparse.ArgumentParser:
    """Build CLI argument parser."""
    parser = argparse.ArgumentParser(description="Verified Release & Tactile UI Craft Helper CLI")
    sub = parser.add_subparsers(dest="command", required=True)

    p_tools = sub.add_parser("check-tools", help="Check availability of external security CLIs")
    p_tools.set_defaults(func=cmd_check_tools)

    p_manifest = sub.add_parser("sha256-manifest", help="Generate SHA-256 manifest for a directory")
    p_manifest.add_argument("--dir", required=True, help="Target artifact directory")
    p_manifest.add_argument("--out", required=False, help="Output manifest JSON path")
    p_manifest.set_defaults(func=cmd_sha256_manifest)

    p_verify = sub.add_parser("verify-manifest", help="Verify artifacts against SHA-256 manifest")
    p_verify.add_argument("--manifest", required=True, help="Path to SHA256SUMS.json")
    p_verify.add_argument("--dir", required=False, help="Override base directory")
    p_verify.set_defaults(func=cmd_verify_manifest)

    p_crypto = sub.add_parser("check-crypto-patterns", help="Scan for weak crypto anti-patterns")
    p_crypto.add_argument("--dir", required=True, help="Source directory to scan")
    p_crypto.set_defaults(func=cmd_check_crypto_patterns)

    p_ui = sub.add_parser("audit-ui-slop", help="Scan frontend files for generic AI slop chrome")
    p_ui.add_argument("--dir", required=True, help="Frontend source directory to scan")
    p_ui.set_defaults(func=cmd_audit_ui_slop)

    return parser


def main(argv: List[str] | None = None) -> int:
    """CLI entry point."""
    parser = build_parser()
    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    sys.exit(main())
